window.runArcadeTests=()=>{
  const g=window.pigeonGame,results=[];
  const check=(name,ok)=>{if(!ok)throw new Error(name);results.push(name)};
  check('Arcade state exposes the final frenzy',typeof g.state.frenzy==='boolean');
  const advance=seconds=>{for(let left=seconds;left>1e-8;left-=1/120)g.step(Math.min(left,1/120),0)};
  const start=(count=1)=>{document.querySelector(`[data-players="${count}"]`).click();document.getElementById('play').click();g.step(3.61,0);g.skipDiscoveries();g.quietPickups()};
  start();g.warnHawk(2.8);advance(3);
  check('Passing close to a hawk earns 75 points without a collision',g.state.players[0].nearMisses===1&&g.state.players[0].score===75&&g.state.players[0].clips===0);
  advance(1);check('Each hawk grants its near-miss bonus only once',g.state.players[0].score===75);
  start();g.warnHawk(6);advance(3);
  check('A distant hawk pass does not earn a near-miss bonus',g.state.players[0].nearMisses===0&&g.state.players[0].score===0);
  start();g.warnHawk(2.19);advance(3);
  check('A collision cannot also count as a near miss',g.state.players[0].clips===1&&g.state.players[0].nearMisses===0);
  start(2);g.warnHawk(0);advance(3);
  check('Both players can earn their own close-shave bonus',g.state.players.every(p=>p.nearMisses===1&&p.score===75));
  start();advance(49.99);
  check('Frenzy stays off until the last ten seconds',!g.state.frenzy);
  advance(.02);
  check('Frenzy starts with ten seconds left',g.state.frenzy&&g.state.time<10&&g.state.time>9.9);
  check('The HUD explains double splat points',document.getElementById('frenzyBadge').textContent.includes('×2')&&!document.getElementById('frenzyBadge').hidden);
  const before=g.state.time;document.getElementById('pause').click();g.step(4,0);
  check('Pausing freezes the frenzy countdown',g.state.time===before);
  document.getElementById('pause').click();
  g.setupTarget('Car',0,13-(g.state.speed+4)*.24);g.quietPickups();g.drop(0);advance(.25);
  check('A bullseye earns double splat points during frenzy',g.state.players[0].score===100);
  start();advance(50.01);g.setupTarget('Car',0,0);g.quietPickups();g.spawnPickup('bomb',0,13);g.step(0,0);
  check('Frenzy doubles bomb target points but not the pickup bonus',g.state.players[0].score===150);
  advance(10);
  check('The round ends on time and removes frenzy UI',g.state.mode==='over'&&g.state.time===0&&!g.state.frenzy&&document.getElementById('frenzyBadge').hidden);
  start();check('Replay clears near misses and frenzy',g.state.players[0].nearMisses===0&&g.state.players[0].score===0&&!g.state.frenzy);
  g.setupTarget('Car',0,13-30*.24);g.drop(0);advance(.25);
  check('Ordinary rounds keep normal point values',g.state.players[0].score===50);
  return results;
};
