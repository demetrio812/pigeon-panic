// Browser integration checks: load the game with ?test=1, then run runPickupTests().
window.runPickupTests = () => {
  const g = window.pigeonGame, results = [];
  g.skipDiscoveries();
  const check = (name, condition) => { if (!condition) throw new Error(name); results.push(name); };
  check('Collectibles can be spawned for a controlled round', typeof g.spawnPickup === 'function');
  const advance = seconds => { for (let left = seconds; left > 1e-8; left -= 1 / 120) g.step(Math.min(left, 1 / 120), 0); };
  const start = (count = 1) => {
    if (g.state.mode === 'paused') document.getElementById('pause').click();
    document.querySelector(`[data-players="${count}"]`).click();
    document.getElementById('play').click();
    g.step(3.61, 0);
    g.quietPickups();
  };
  const collect = (kind, i = 0) => { g.spawnPickup(kind, g.state.players[i].x, 13); g.step(0, 0); };
  start();
  collect('slow');
  check('Contact awards 50 points and immediately activates slow motion', g.state.players[0].score === 50 && g.state.slowRemaining === 10);
  g.step(0, 0);
  check('Slow motion reduces street speed', g.state.worldScale === .45);
  const before = g.state.time;
  advance(1);
  check('Round clock runs at normal speed during slow motion', Math.abs(g.state.time - (before - 1)) < .001);
  document.getElementById('pause').click();
  const paused = g.state.slowRemaining;
  g.step(3, 0);
  check('Pause freezes power duration', g.state.slowRemaining === paused);
  document.getElementById('pause').click();
  collect('slow');
  check('Repeat pickup refreshes to ten seconds', g.state.slowRemaining === 10);
  advance(10.01);
  check('Slow motion expires after ten playing seconds', g.state.slowRemaining === 0 && g.state.worldScale === 1);
  start();
  g.setupTarget('Car', 3, 13 - 30 * .24);
  g.quietPickups();
  g.drop(0); advance(.25);
  check('Normal drop misses a target three units sideways', !g.state.targets[0].hit);
  start();
  g.setupTarget('Car', 3, 13 - 30 * .24);
  g.quietPickups();
  collect('super');
  g.drop(0); advance(.25);
  check('Super splat reaches the same off-centre target', g.state.targets[0].hit && g.state.players[0].hits === 1);
  check('Super splat has a visible remaining timer', document.getElementById('powerStatus').textContent.includes('Super splat'));
  advance(10);
  check('Super splat expires', g.state.players[0].superRemaining === 0);
  start();
  g.setupTarget('Car', 0, 0);
  g.placeTarget('Bicycle', 7, -8);
  g.placeTarget('Car', 0, -100);
  collect('bomb');
  check('Bomb hits all visible targets but leaves offscreen traffic', g.state.targets.filter(t => t.hit).length === 2);
  check('Bomb awards base target points plus pickup bonus', g.state.players[0].score === 180);
  check('Bomb does not inflate shot accuracy', g.state.players[0].hits === 0 && g.state.players[0].shots === 0);
  collect('bomb');
  check('Already splatted targets cannot score twice', g.state.players[0].score === 230);
  start(2);
  collect('super', 1);
  check('Super splat and pickup points belong to the collector', g.state.players[0].superRemaining === 0 && g.state.players[1].superRemaining === 10 && g.state.players[1].score === 50 && g.state.players[0].score === 0);
  collect('slow', 1); g.step(0, 0);
  check('Slow motion affects the shared street', g.state.worldScale === .45);
  start();
  check('New round clears powers, pickups, and bonus scores', g.state.slowRemaining === 0 && g.state.players[0].superRemaining === 0 && g.state.players[0].score === 0 && g.state.pickups.length === 0);
  const travel = slow => {
    start();g.setupTarget('Car', 0, -20);g.quietPickups();
    if(slow)collect('slow');
    window.dispatchEvent(new KeyboardEvent('keydown',{key:'d'}));
    advance(.5);
    window.dispatchEvent(new KeyboardEvent('keyup',{key:'d'}));
    return {road:g.state.targets[0].z+20,bird:g.state.players[0].x};
  };
  const normal=travel(false),slow=travel(true);
  check('Slow motion slows actual traffic without slowing steering', Math.abs(slow.road/normal.road-.45)<.001 && Math.abs(slow.bird-normal.bird)<.001);
  start();collect('slow');g.warnHawk(0);advance(1.4);
  check('Slow motion also slows the hawk approach', g.state.hawk.phase==='warning');
  start();g.setupTarget('Car',-2.8,13-30*.24);g.quietPickups();g.placeTarget('Car',2.8,13-30*.24);collect('super');g.drop(0);advance(.25);
  check('Super splat can hit several targets while counting one successful shot', g.state.targets.filter(t=>t.hit).length===2 && g.state.players[0].hits===1 && g.state.players[0].shots===1);
  start();document.getElementById('visualCues').checked=false;document.getElementById('play').click();g.step(3.61,0);g.quietPickups();collect('super');g.warnHawk(0);
  check('Powers preserve the disabled visual-cues setting', !g.state.players[0].guideVisible && !g.state.hawk.laneVisible);
  document.getElementById('visualCues').checked=true;
  document.getElementById('play').click();g.step(3.61,0);advance(2.6);
  check('Pickups spawn naturally during a round', g.state.pickups.length>0);
  advance(57.5);
  check('A full round ends after sixty seconds and clears pickups and timers', g.state.mode==='over' && g.state.time===0 && g.state.pickups.length===0 && document.getElementById('powerStatus').hidden);
  return results;
};
