window.runRoundFlowTests=()=>{
 const g=pigeonGame,r=[];
 const check=(name,ok)=>{if(!ok)throw new Error(name);r.push(name)};
 const advance=s=>{for(let left=s;left>1e-8;left-=1/120)g.step(Math.min(left,1/120),0)};
 const start=()=>{if(g.state.mode==='over')document.getElementById('raceAgain').click();document.getElementById('play').click();g.step(3.61,0);g.skipDiscoveries();g.quietPickups()};
 const collect=kind=>{g.spawnPickup(kind,g.state.players[0].x,13);g.step(0,0)};
 start();g.setupTarget('Car',0,0);g.placeTarget('Car',5,-10);g.quietPickups();collect('slow');advance(.5);collect('bomb');
 check('Bomb splats traffic and awards points during slow motion',g.state.targets.every(t=>t.hit)&&g.state.players[0].score===200&&g.state.slowRemaining>9);
 check('Car splat marks sit above the roof',g.state.targets.every(t=>t.markY>1.75));
 check('Bomb gives explicit hit feedback',document.getElementById('bombFeedback').textContent.includes('2 targets'));
 collect('bomb');check('A bomb with no fresh targets explains why',document.getElementById('bombFeedback').textContent.includes('No fresh targets'));
 g.resetDiscoveries();collect('super');
 window.dispatchEvent(new KeyboardEvent('keydown',{key:' ',repeat:true}));
 check('Held fire cannot accidentally dismiss a discovery',g.state.mode==='discovery');
 window.dispatchEvent(new KeyboardEvent('keydown',{key:' '}));
 check('Space dismisses the discovery without firing a shot',g.state.mode==='playing'&&g.state.players[0].shots===0);
 window.dispatchEvent(new KeyboardEvent('keyup',{key:' '}));
 collect('bomb');window.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter'}));
 check('Enter also dismisses the discovery',g.state.mode==='playing');
 window.dispatchEvent(new KeyboardEvent('keyup',{key:'Enter'}));
 g.skipDiscoveries();advance(60.05);
 check('Round end shows a separate results card',document.getElementById('results').open&&document.getElementById('overlay').classList.contains('hidden'));
 check('The score is prominent in the results',+document.querySelector('.result-score').dataset.score===g.state.players[0].score);
 const score=g.state.players[0].score;
 document.getElementById('raceAgain').click();
 check('Race again returns to character selection without starting',g.state.mode==='intro'&&!document.getElementById('results').open&&!document.getElementById('options').hidden&&!document.getElementById('overlay').classList.contains('hidden'));
 check('Selection restores the original welcome text',document.getElementById('play').textContent==='Hit the road'&&document.getElementById('title').textContent.includes('Express'));
 document.getElementById('play').click();
 check('Starting from selection resets score and runs countdown',g.state.mode==='countdown'&&g.state.players[0].score===0);
 g.step(3.61,0);g.skipDiscoveries();g.quietPickups();advance(60.05);
 check('A zero-score run has clear, valid statistics',document.getElementById('results').open&&g.state.players[0].score===0&&document.getElementById('results').textContent.includes('0%')&&!document.getElementById('results').textContent.includes('NaN'));
 document.getElementById('raceAgain').click();document.querySelector('[data-players="2"]').click();start();advance(60.05);
 check('Two-player results show both players and a draw',document.querySelectorAll('.result-player').length===2&&document.getElementById('resultsTitle').textContent.includes('draw'));
 return r;
};
