window.runDiscoveryTests = () => {
  const g=window.pigeonGame, results=[];
  const check=(name,ok)=>{if(!ok)throw new Error(name);results.push(name)};
  check('Discovery reset fixture is available',typeof g.resetDiscoveries==='function');
  g.resetFlock();g.resetDiscoveries();
  const start=()=>{document.getElementById('play').click();g.step(3.61,0);g.quietPickups()};
  const collect=(kind,x=0)=>{g.spawnPickup(kind,x,13);g.step(0,0)};
  start();collect('slow');
  check('First pickup opens its discovery card and pauses play',g.state.mode==='discovery'&&document.getElementById('discovery').open&&document.getElementById('discoveryTitle').textContent==='Slow motion');
  const before=JSON.stringify(g.state);g.step(5,5000);
  check('Reading the card freezes the complete game state',JSON.stringify(g.state)===before);
  check('The power is saved until continuing',g.state.slowRemaining===0&&g.state.players[0].score===0);
  document.getElementById('pause').click();
  window.dispatchEvent(new KeyboardEvent('keydown',{key:' ',repeat:true}));
  check('Pause and held firing cannot bypass the discovery card',g.state.mode==='discovery'&&g.state.players[0].shots===0);
  document.getElementById('discoveryContinue').click();
  check('Continue grants the full power duration and bonus once',g.state.mode==='playing'&&g.state.slowRemaining===10&&g.state.players[0].score===50);
  document.getElementById('discoveryContinue').click();
  check('Repeated continue does not grant duplicate points',g.state.players[0].score===50);
  check('Acknowledged discovery is persisted',JSON.parse(localStorage.getItem('pigeonPowerDiscoveriesV1')).includes('slow'));
  collect('slow');
  check('Repeat collection activates without interruption',g.state.mode==='playing'&&g.state.players[0].score===100);
  collect('super');
  check('A different power gets its own discovery',g.state.mode==='discovery'&&document.getElementById('discoveryTitle').textContent==='Super splat');
  document.getElementById('discoveryContinue').click();
  start();g.setupTarget('Car',0,0);g.quietPickups();collect('bomb');
  check('Bomb waits for its introduction before splatting targets',g.state.mode==='discovery'&&!g.state.targets[0].hit);
  document.getElementById('discoveryContinue').click();
  check('Bomb detonates on continue',g.state.targets[0].hit&&g.state.players[0].score===100);
  start();collect('super');
  check('A re-enabled tutorial introduces powers again each round',g.state.mode==='discovery');
  document.getElementById('discoveryContinue').click();
  g.resetDiscoveries();document.querySelector('[data-players="2"]').click();start();collect('super',3);
  check('Two-player card identifies the collecting player',g.state.mode==='discovery'&&document.getElementById('discoveryOwner').textContent.includes('P2'));
  document.getElementById('discoveryContinue').click();
  check('Continuing gives the power to the correct player',g.state.players[0].superRemaining===0&&g.state.players[1].superRemaining===10);
  return results;
};
